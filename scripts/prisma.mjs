#!/usr/bin/env node
// Runs the Prisma CLI against the right provider.
//
// prisma/schema.prisma is written for PostgreSQL (production). When DATABASE_URL points at a
// SQLite file ("file:..."), this script writes prisma/.generated/schema.prisma with the provider
// swapped to "sqlite" and runs Prisma against that copy instead. Everything else is passed through.
//
//   node scripts/prisma.mjs generate
//   node scripts/prisma.mjs db push
//   node scripts/prisma.mjs migrate deploy
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');
if (!process.env.DATABASE_URL && existsSync(envFile)) {
  process.loadEnvFile(envFile);
}

const args = process.argv.slice(2);
const canonical = join(root, 'prisma', 'schema.prisma');
let schemaPath = canonical;

const url = process.env.DATABASE_URL ?? '';
if (url.startsWith('file:')) {
  const source = readFileSync(canonical, 'utf8');
  const sqlite = source.replace(/provider\s*=\s*"postgresql"/, 'provider = "sqlite"');
  if (sqlite === source) {
    console.error(
      'scripts/prisma.mjs: could not find the postgresql provider in prisma/schema.prisma',
    );
    process.exit(1);
  }
  const outDir = join(root, 'prisma', '.generated');
  mkdirSync(outDir, { recursive: true });
  schemaPath = join(outDir, 'schema.prisma');
  writeFileSync(
    schemaPath,
    `// GENERATED by scripts/prisma.mjs from prisma/schema.prisma. Do not edit.\n${sqlite}`,
  );
  if (args[0] === 'migrate') {
    console.error(
      'Migrations target PostgreSQL. For a local SQLite database use "pnpm db:push" instead.',
    );
    process.exit(1);
  }
}

if (args[0] === 'generate' && !url) {
  // Generating the client does not need a database; give Prisma a placeholder URL.
  process.env.DATABASE_URL = 'postgresql://placeholder:placeholder@localhost:5432/placeholder';
}

const localBin = join(
  root,
  'node_modules',
  '.bin',
  process.platform === 'win32' ? 'prisma.cmd' : 'prisma',
);
const prismaBin = existsSync(localBin) ? localBin : 'prisma';
const result = spawnSync(prismaBin, [...args, '--schema', schemaPath], {
  cwd: root,
  stdio: 'inherit',
  env: process.env,
  shell: process.platform === 'win32',
});
process.exit(result.status ?? 1);
